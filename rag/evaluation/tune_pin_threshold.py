"""
evaluation/tune_pin_threshold.py
Gap 6 fix: empirically tune MIN_PIN_SIMILARITY for the section pinner.

Sweeps thresholds in [0.50, 0.55, 0.60, 0.65, 0.70, 0.75] and measures
Precision@K and Recall@K against a benchmark file's gold sections.

IMPORTANT — leakage fix: this now defaults to benchmark_scenarios_dev.json
(generated by evaluation/split_benchmark.py), NOT the full
benchmark_scenarios.json. Tuning this threshold against the same file
evaluate.py reports final numbers on would fit the threshold to the test
set, inflating the reported Recall/Precision. Run
`python3 evaluation/split_benchmark.py` once to generate the dev/test
files if they don't exist yet; report final metrics with evaluate.py
against benchmark_scenarios_test.json.

Usage:
    python3 evaluation/tune_pin_threshold.py
    python3 evaluation/tune_pin_threshold.py evaluation/benchmark_scenarios_dev.json
"""
import json
import sys
from pathlib import Path

sys.path.append(str(Path(__file__).parent.parent))
from config import QDRANT_PATH, EMBEDDING_MODEL, COLLECTION_NAME
from pipeline.section_pinner import SectionPinner
from pipeline.hybrid_retriever import BGE_QUERY_INSTRUCTION


THRESHOLDS = [0.50, 0.55, 0.60, 0.65, 0.70, 0.75]

_DEFAULT_DEV_PATH = "./evaluation/benchmark_scenarios_dev.json"
_FALLBACK_PATH = "./evaluation/benchmark_scenarios.json"


def _resolve_default_path() -> str:
    if Path(_DEFAULT_DEV_PATH).exists():
        return _DEFAULT_DEV_PATH
    print(f"[tune_pin] WARNING: {_DEFAULT_DEV_PATH} not found — run "
          f"`python3 evaluation/split_benchmark.py` first. Falling back to "
          f"{_FALLBACK_PATH}, which means this threshold will be tuned on "
          f"the same data evaluate.py reports final numbers on (leakage).")
    return _FALLBACK_PATH


def sweep(benchmark_path: str | None = None):
    benchmark_path = benchmark_path or _resolve_default_path()
    from qdrant_client import QdrantClient
    from sentence_transformers import SentenceTransformer

    print("[tune_pin] Loading Qdrant client and bge-large model...")
    client = QdrantClient(path=QDRANT_PATH)
    model  = SentenceTransformer(EMBEDDING_MODEL)
    # BUGFIX: SectionPinner dense-searches the passage-embedded
    # "legal_sections" collection, so the query side needs the same
    # bge-large asymmetric instruction prefix HybridRetriever uses (see
    # main.py's pin_embed_fn wiring note). The old unprefixed embed_fn
    # here meant every threshold in this sweep — including the
    # MIN_PIN_SIMILARITY=0.62 default currently in section_pinner.py — was
    # tuned against systematically depressed similarity scores. Re-run this
    # sweep after pulling the fix; the recommended threshold will likely
    # come out higher now that matches score correctly.
    embed_fn = lambda texts: [
        model.encode(f"{BGE_QUERY_INSTRUCTION}{t}", normalize_embeddings=True).tolist()
        for t in texts
    ]

    with open(benchmark_path) as f:
        benchmark = json.load(f)

    print(f"[tune_pin] {len(benchmark)} benchmark queries | "
          f"sweeping thresholds: {THRESHOLDS}\n")
    print(f"{'Threshold':>10}  {'Precision@K':>11}  {'Recall@K':>9}  {'F1':>6}  {'Avg pins':>8}")
    print("-" * 55)

    best_f1, best_thresh = 0.0, 0.62
    results = []

    for thresh in THRESHOLDS:
        pinner = SectionPinner(client=client, embed_fn=embed_fn,
                               min_similarity=thresh, top_k=6)
        precisions, recalls, n_pins = [], [], []

        for item in benchmark:
            gold = set(item.get("gold_sections", []))
            if not gold:
                continue
            pin = pinner.pin(item["query"])
            pinned = set(pin.section_ids)
            n_pins.append(len(pinned))

            if pinned:
                prec = len(pinned & gold) / len(pinned)
                rec  = len(pinned & gold) / len(gold)
            else:
                prec, rec = 0.0, 0.0

            precisions.append(prec)
            recalls.append(rec)

        avg_p   = sum(precisions) / len(precisions) if precisions else 0.0
        avg_r   = sum(recalls)    / len(recalls)    if recalls    else 0.0
        avg_f1  = (2 * avg_p * avg_r / (avg_p + avg_r)) if (avg_p + avg_r) > 0 else 0.0
        avg_pin = sum(n_pins) / len(n_pins) if n_pins else 0.0

        marker = " ← best" if avg_f1 > best_f1 else ""
        if avg_f1 > best_f1:
            best_f1, best_thresh = avg_f1, thresh

        print(f"{thresh:>10.2f}  {avg_p:>11.3f}  {avg_r:>9.3f}  "
              f"{avg_f1:>6.3f}  {avg_pin:>8.1f}{marker}")
        results.append((thresh, avg_p, avg_r, avg_f1))

    print(f"\n[tune_pin] Recommended MIN_PIN_SIMILARITY = {best_thresh:.2f} (F1={best_f1:.3f})")
    print(f"  Set this in pipeline/section_pinner.py line ~46:\n"
          f"  MIN_PIN_SIMILARITY = {best_thresh:.2f}")
    return best_thresh


if __name__ == "__main__":
    path = sys.argv[1] if len(sys.argv) > 1 else None
    sweep(path)